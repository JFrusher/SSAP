const EYES: Partial<Record<CardName, [number, number][]>> = {
  crab: [[20, 14], [28, 14]], fish: [[14, 22]], shark: [[38, 26]], octopus: [[20, 16], [28, 16]], penguin: [[22, 10], [26, 10]],
};

function mix(hex: string, target: number, amount: number): string {
  const n = parseInt(hex.slice(1), 16);
  const ch = (shift: number) => Math.round(((n >> shift) & 255) * (1 - amount) + target * amount);
  return `rgb(${ch(16)}, ${ch(8)}, ${ch(0)})`;
}

function tones(color: Color | null): Record<"L" | "M" | "D", string> {
  if (color === null) return { L: "#E9E2D3", M: "#CFC5B2", D: "#9C917D" }; // neutral paper before a colour is chosen
  if (color === "white") return { L: "#FFFFFF", M: "#ECE6DA", D: "#C9BFAD" };
  const base = SWATCH[color];
  return { L: mix(base, 255, 0.38), M: base, D: mix(base, 0, 0.3) };
}

export function CardArt({ name, color, className }: { name: CardName; color: Color | null; className?: string }) {
  const t = tones(color);
  return (
    <svg viewBox="0 0 48 48" className={className} aria-hidden="true">
      {ART[name].map(([tone, pts], i) => <polygon key={i} points={pts} fill={t[tone]} />)}
      {EYES[name]?.map(([cx, cy], i) => <circle key={`e${i}`} cx={cx} cy={cy} r={1.4} fill="#1F1D1A" />)}
    </svg>
  );
}
